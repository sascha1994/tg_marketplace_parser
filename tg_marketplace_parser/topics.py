def product_topic(category: str, title: str, *, today: date | None = None) -> str | None:
    category = category.casefold().replace("ё", "е").strip()
    title = title.casefold().replace("ё", "е").strip()
    category_parts = category_path_parts(category)
    if (today or date.today()) <= HOLIDAY_TOPIC_LAST_DAY and (
        HOLIDAY_PRODUCTS.search(title)
        or HOLIDAY_PRODUCTS.search(category)
        or HOLIDAY_CATEGORIES.intersection(category_parts)
    ):
        return HOLIDAY_TOPIC

    audience = f"{category} {title}"
    child = CHILD.search(audience) is not None
    clothing_topic = CHILD_CLOTHING_TOPIC if child else ADULT_CLOTHING_TOPIC

    for pattern, topic in TITLE_PHRASES:
        if pattern.search(title):
            return clothing_topic if topic == ADULT_CLOTHING_TOPIC else topic

    if TECHNICAL_DRYER.search(title):
        return TECH_TOPIC
    if HAIR_STYLING.search(title):
        return BEAUTY_TOPIC

    if not ADULT.search(audience) and (
        (COLORING.search(audience) and (child or "антистресс" not in audience))
        or (child and KIDS_CRAFTS.search(audience))
    ):
        return CHILD_GOODS_TOPIC

    for part in reversed(category_parts):
        if part in CATEGORY_TOPICS:
            mapped = CATEGORY_TOPICS[part]
            return clothing_topic if mapped == ADULT_CLOTHING_TOPIC else mapped

    if "строительство и ремонт" in category_parts:
        for value in (*reversed(category_parts), title):
            power_tool = POWER_TOOLS.search(value)
            repair_item = REPAIR.search(value)
            if power_tool and (repair_item is None or power_tool.start() < repair_item.start()):
                return TECH_TOPIC
            if repair_item:
                break

    for part in reversed(category_parts):
        topic = ROOT_CATEGORY_TOPICS.get(part)
        if topic:
            if child and (topic == ADULT_CLOTHING_TOPIC or (
                part in {"детям", "детские товары"} and CLOTHING.search(audience)
            )):
                return CHILD_CLOTHING_TOPIC
            return topic

    # The earliest specific type in the title takes precedence over descriptors.
    panama_topic = clothing_topic if child or ADULT.search(audience) else None
    product_types = (
        (CLOTHING, clothing_topic), (PANAMA, panama_topic), (TOYS, CHILD_GOODS_TOPIC),
        (TECH, TECH_TOPIC), (POWER_TOOLS, TECH_TOPIC), (HOME, HOME_TOPIC),
        *ADDITIONAL_PRODUCT_TYPES,
    )
    for value in (title, *reversed(category_parts)):
        matches = (
            (match.start(), topic)
            for pattern, topic in product_types
            if (match := pattern.search(value))
        )
        first = min(matches, key=lambda match: match[0], default=None)
        if first:
            return first[1]
    return None


async def find_forum_topic(client, group, title: str):
    # Telegram moved this method from channels to messages across API layers.
    if hasattr(functions.messages, "GetForumTopicsRequest"):
        query = functions.messages.GetForumTopicsRequest(peer=group, offset_date=None,
            offset_id=0, offset_topic=0, limit=100, q=title)
    else:
        query = functions.channels.GetForumTopicsRequest(channel=group, offset_date=None,
            offset_id=0, offset_topic=0, limit=100, q=title)
    result = await client(query)
    return next((t for t in result.topics if getattr(t, "title", None) == title), None)


async def forward_to_topic(client, source, group_id: int, topic_name, message_ids):
    source_peer = await client.get_input_entity(source)
    source_id = utils.get_peer_id(source_peer)
    group = await resolve_forum(client, group_id)
    topic = await find_forum_topic(client, group, topic_name)
    alias = TOPIC_ALIASES.get(topic_name)
    if topic is None and alias:
        topic = await find_forum_topic(client, group, alias)
    if topic is None:
        raise ValueError(f"Не найдена тема {topic_name!r}")
    random_ids = [
        int.from_bytes(hashlib.blake2b(f"{source_id}/{mid}/{group_id}/{topic.id}".encode(),
                                       digest_size=8).digest(), "big", signed=True)
        for mid in message_ids
    ]
    sent = await client(functions.messages.ForwardMessagesRequest(
        from_peer=source_peer, to_peer=group,
        id=message_ids, random_id=random_ids, top_msg_id=topic.id, drop_author=True,
    ))
    ids = {u.random_id: u.id for u in sent.updates if isinstance(u, types.UpdateMessageID)}
    return f"forum:{group_id}", [ids[rid] for rid in random_ids]
